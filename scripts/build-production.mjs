#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────
// build-production.mjs — Production Android AAB build wrapper.
//
// This script wraps the local production build process to ensure
// the production preflight validation ALWAYS runs before any
// AAB is produced. A developer must not have to remember to run
// a separate preflight command.
//
// Usage:
//   node scripts/build-production.mjs          # bundleRelease (AAB)
//   node scripts/build-production.mjs --apk    # assembleRelease (APK)
//
// Process:
//   1. Run production preflight validation
//   2. Run expo prebuild --platform android (regenerates android/)
//   3. Patch android/app/build.gradle to wire preflight to Gradle
//   4. Run ./gradlew bundleRelease (or assembleRelease)
//
// If preflight fails, the build is aborted before step 2.
// ─────────────────────────────────────────────────────────────

import { execSync } from 'node:child_process'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { resolve, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = fileURLToPath(new URL('.', import.meta.url))
const projectRoot = resolve(__dirname, '..')

const isApk = process.argv.includes('--apk')
const gradleTask = isApk ? 'assembleRelease' : 'bundleRelease'

// ── Step 1: Production preflight ─────────────────────────────
console.log('\n┌─────────────────────────────────────────────────────────┐')
console.log('│  RawLifeFlow Production Build — Preflight Validation    │')
console.log('└─────────────────────────────────────────────────────────┘\n')

try {
  // --store: this wrapper always produces a distributable AAB/APK,
  // so monetization must be strictly enabled (see Fix 3, P1 audit).
  execSync('node scripts/preflight-production.mjs --store', {
    cwd: projectRoot,
    stdio: 'inherit',
  })
} catch {
  console.error('\n✗ Production preflight FAILED. Build aborted.')
  console.error('  Fix the configuration issues above before retrying.\n')
  process.exit(1)
}

console.log('\n✓ Preflight passed. Proceeding with build...\n')

// ── Step 2: Expo prebuild ────────────────────────────────────
console.log('┌─────────────────────────────────────────────────────────┐')
console.log('│  Step 2: expo prebuild --platform android               │')
console.log('└─────────────────────────────────────────────────────────┘\n')

execSync('npx expo prebuild --platform android --clean', {
  cwd: projectRoot,
  stdio: 'inherit',
})

// ── Step 3: Patch build.gradle to wire preflight ─────────────
console.log('\n┌─────────────────────────────────────────────────────────┐')
console.log('│  Step 3: Wiring preflight to Gradle build               │')
console.log('└─────────────────────────────────────────────────────────┘\n')

const gradlePath = join(projectRoot, 'android', 'app', 'build.gradle')
if (!existsSync(gradlePath)) {
  console.error('✗ android/app/build.gradle not found after prebuild. Aborting.')
  process.exit(1)
}

let gradleContent = readFileSync(gradlePath, 'utf8')

// Only patch if not already patched
if (!gradleContent.includes('preflightProduction')) {
  const preflightTask = `
// ── Production preflight validation ──────────────────────────
// Auto-generated by scripts/build-production.mjs
// Runs the Node.js preflight before bundleRelease/assembleRelease.
task preflightProduction(type: Exec) {
    workingDir projectRoot
    commandLine 'node', 'scripts/preflight-production.mjs', '--store'
    onlyIf {
        gradle.startParameter.taskNames.any { name ->
            name.toLowerCase().contains('release')
        }
    }
}

tasks.matching { task ->
    task.name == 'bundleRelease' || task.name == 'assembleRelease'
}.configureEach { task ->
    task.dependsOn 'preflightProduction'
}
`

  // Append the preflight task at the end of the file
  gradleContent = gradleContent + '\n' + preflightTask
  writeFileSync(gradlePath, gradleContent)
  console.log('✓ Patched android/app/build.gradle with preflight task')
} else {
  console.log('✓ android/app/build.gradle already has preflight task')
}

// ── Step 4: Gradle build ─────────────────────────────────────
console.log('\n┌─────────────────────────────────────────────────────────┐')
console.log(`│  Step 4: ./gradlew ${gradleTask}                        │`)
console.log('└─────────────────────────────────────────────────────────┘\n')

const gradleCmd = process.platform === 'win32'
  ? `cd android && .\\gradlew.bat ${gradleTask}`
  : `cd android && ./gradlew ${gradleTask}`

execSync(gradleCmd, {
  cwd: projectRoot,
  stdio: 'inherit',
})

console.log('\n✓ Production build completed successfully.\n')
